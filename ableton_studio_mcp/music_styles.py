def style_key(name: str) -> str:
    key = str(name).strip().lower().replace("-", "_").replace(" ", "_")
    if key in STYLES:
        return key
    alias = _ALIASES.get(str(name).strip().lower())
    if alias:
        return alias
    raise KeyError("Unknown style '%s'. Known: %s" % (name, ", ".join(sorted(STYLES))))


def list_styles() -> List[Dict]:
    return [{"style": k, "label": v["label"], "tempo": v["tempo"], "scales": v["scales"]}
            for k, v in STYLES.items()]


def get_style(name: str) -> Dict:
    k = style_key(name)
    return dict(STYLES[k], style=k)
